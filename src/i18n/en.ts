const SERVER_PATTERNS: ReadonlyArray<readonly [RegExp, (m: RegExpMatchArray) => string]> = [
  [/^(.+) saknar (.+)\.$/, (m) => `${placeName(m[1]!)} is missing ${m[2]}.`],
  [
    /^(.+) har bara (\d+) (.+) kvar\. Det går inte att ångra\.$/,
    (m) => `${placeName(m[1]!)} only has ${m[2]} ${m[3]} left. It cannot be undone.`,
  ],
  [
    /^För många (?:försök|länkar)\. Vänta (\d+) (?:minut|minuter)\.$/,
    (m) => `Too many attempts. Wait ${m[1]} ${m[1] === "1" ? "minute" : "minutes"}.`,
  ],
  [/^Lagret (.+) har bara (\d+) /, (m) => `${placeName(m[1]!)} only has ${m[2]} packs.`],
];

function serverError(message: string): string {
  const exact = SERVER_EXACT[message.trim()];
  if (exact) return exact;
  for (const [re, to] of SERVER_PATTERNS) {
    const m = message.trim().match(re);
    if (m) return to(m);
  }
  return "Something went wrong. Try again, or ask the owner.";
}

